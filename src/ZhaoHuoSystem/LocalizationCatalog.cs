    private static readonly Dictionary<string, int> Indices = Build();
    private static readonly Dictionary<string, int> DisplayIndices = BuildDisplay();
    private static Dictionary<string, int> Build()
    {
        var result = new Dictionary<string, int>(StringComparer.Ordinal);
        for (int i = 0; i < Rows.GetLength(0); i++) result.Add(Rows[i, 0], i);
        return result;
    }

    private static Dictionary<string, int> BuildDisplay()
    {
        var result = new Dictionary<string, int>(Indices, StringComparer.Ordinal);
        for (int i = 0; i < Rows.GetLength(0); i++)
            if (!result.ContainsKey(Rows[i, 1])) result.Add(Rows[i, 1], i);
        return result;
    }

    internal static string Get(string language, string source)
    {
        if (source == null) return "";
        if (language == English || language == Japanese) return Extra(language).TryGetValue(source, out var translated) ? translated : source;
        if (!Indices.TryGetValue(source, out int row)) return source;
        return Rows[row, language == Traditional ? 1 : language == Korean ? 2 : 0];
    }
    /// <summary>English or Japanese by Simplified source (LocalizationCatalog.English.cs, .Japanese.cs).</summary>
    /// <summary>The source of copy saved in any of the panel's languages, to show it in the current one; else the text itself.</summary>
    internal static string SourceOf(string text)
    {
        if (Indices.ContainsKey(text)) return text;
        for (int row = 0; row < Rows.GetLength(0); row++)
            if (Rows[row, 1] == text || Rows[row, 2] == text) return Rows[row, 0];
        foreach (var rows in new[] { EnglishRows, JapaneseRows })
            foreach (var pair in rows)
                if (pair.Value == text) return pair.Key;
        return text;
    }
    internal static Dictionary<string, string> Extra(string language) => language == English ? EnglishRows : JapaneseRows;
    internal static bool Has(string language, string source) => language == English || language == Japanese ? Extra(language).ContainsKey(source) : Indices.ContainsKey(source);

    internal static bool Contains(string source) => Indices.ContainsKey(source);
    internal static bool TryDisplay(string source, string language, out string value)
    {
        if (DisplayIndices.TryGetValue(source, out int row))
        {
            value = language == English || language == Japanese ? Get(language, Rows[row, 0]) : Rows[row, language == Traditional ? 1 : language == Korean ? 2 : 0];
            return true;
        }
        value = source;
        return false;
    }
    internal static string OfficialLanguage(string? language) => language == Traditional ? Traditional : language == Korean ? Korean : Simplified;
